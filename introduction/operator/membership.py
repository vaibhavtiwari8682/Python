"""
in Python, the membership operator is used to test whether a value or variable is found in a sequence (such as a string, list, tuple, set, or dictionary). The membership operators are:
in - returns True if a sequence with the specified value is present in the object
not in - returns True if a sequence with the specified value is not present in the object

"""

vegetables = ['carrot', 'potato', 'tomato']
print('carrot' in vegetables) # True, because 'carrot' is present in the list
print('onion' in vegetables) # False, because 'onion' is not present in the list
print('onion' not in vegetables) # True, because 'onion' is not present in the list