x = 10
print(x) # assignment operator assigns the value to the variable
x +=5
print(x) # addition assignment operator adds the value to the variable
x -=5   
print(x) # subtraction assignment operator subtracts the value from the variable
x *=5
print(x) # multiplication assignment operator multiplies the value to the variable
x /=5
print(x) # division assignment operator divides the value from the variable